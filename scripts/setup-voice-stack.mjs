#!/usr/bin/env node
/**
 * One-time setup: whisper.cpp + Piper models for local Jarvis voice stack.
 */
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, writeFileSync, chmodSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createWriteStream } from 'node:fs'
import { pipeline } from 'node:stream/promises'
import { Readable } from 'node:stream'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const TOOLS = path.join(ROOT, 'tools')
const WHISPER_DIR = path.join(TOOLS, 'whisper.cpp')
const WHISPER_MODELS = path.join(WHISPER_DIR, 'models')
const PIPER_DIR = path.join(TOOLS, 'piper')
const ENV_LOCAL = path.join(ROOT, '.env.local')

function log(msg) {
  console.log(`[setup] ${msg}`)
}

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { stdio: 'inherit', ...opts })
  if (r.status !== 0) throw new Error(`${cmd} failed (${r.status})`)
}

async function download(url, dest) {
  if (existsSync(dest)) {
    log(`exists: ${path.basename(dest)}`)
    return
  }
  log(`downloading ${url}`)
  mkdirSync(path.dirname(dest), { recursive: true })
  const res = await fetch(url)
  if (!res.ok) throw new Error(`Download failed ${url}: ${res.status}`)
  await pipeline(Readable.fromWeb(res.body), createWriteStream(dest))
}

async function main() {
  mkdirSync(WHISPER_MODELS, { recursive: true })
  mkdirSync(PIPER_DIR, { recursive: true })

  if (!spawnSync('which', ['brew'], { encoding: 'utf8' }).stdout?.trim()) {
    throw new Error('Homebrew required')
  }

  if (!spawnSync('which', ['whisper-cli'], { encoding: 'utf8' }).stdout?.trim()) {
    log('Installing whisper-cpp via Homebrew…')
    spawnSync('brew', ['install', 'whisper-cpp'], { stdio: 'inherit' })
    if (!spawnSync('which', ['whisper-cli'], { encoding: 'utf8' }).stdout?.trim()) {
      throw new Error('whisper-cli not found after brew install')
    }
  } else {
    log('whisper-cli already installed')
  }

  const whisperBin =
    spawnSync('which', ['whisper-cli'], { encoding: 'utf8' }).stdout?.trim() ||
    '/opt/homebrew/bin/whisper-cli'

  const whisperModel = path.join(WHISPER_MODELS, 'ggml-base.en.bin')
  await download(
    'https://huggingface.co/ggerganov/whisper.cpp/resolve/main/ggml-base.en.bin',
    whisperModel
  )

  const arch = process.arch === 'arm64' ? 'aarch64' : 'x86_64'
  const piperTar = path.join(PIPER_DIR, 'piper.tar.gz')
  const piperUrl = `https://github.com/rhasspy/piper/releases/download/2023.11.14-2/piper_macos_${arch}.tar.gz`

  if (!existsSync(path.join(PIPER_DIR, 'piper', 'piper'))) {
    await download(piperUrl, piperTar)
    run('tar', ['-xzf', piperTar, '-C', PIPER_DIR])
    try {
      chmodSync(path.join(PIPER_DIR, 'piper', 'piper'), 0o755)
    } catch {}
  } else {
    log('piper tarball already extracted')
  }

  const venvPiper = path.join(ROOT, 'tools/chatterbox/.venv/bin/piper')
  const venvPython = path.join(ROOT, 'tools/chatterbox/.venv/bin/pip')
  if (existsSync(venvPython) && !existsSync(venvPiper)) {
    log('Installing piper-tts into Chatterbox venv…')
    run(venvPython, ['install', 'piper-tts'])
  } else if (existsSync(venvPiper)) {
    log('piper CLI already in Chatterbox venv')
  }

  const piperOnnx = path.join(PIPER_DIR, 'en_GB-alan-medium.onnx')
  const piperJson = `${piperOnnx}.json`
  await download(
    'https://huggingface.co/rhasspy/piper-voices/resolve/main/en/en_GB/alan/medium/en_GB-alan-medium.onnx',
    piperOnnx
  )
  await download(
    'https://huggingface.co/rhasspy/piper-voices/resolve/main/en/en_GB/alan/medium/en_GB-alan-medium.onnx.json',
    piperJson
  )

  const env = `# Auto-generated by scripts/setup-voice-stack.mjs
WHISPER_CPP_BIN=${whisperBin}
WHISPER_MODEL=${whisperModel}
PIPER_BIN=${existsSync(venvPiper) ? venvPiper : path.join(PIPER_DIR, 'piper', 'piper')}
PIPER_MODEL=${piperOnnx}
PIPER_CONFIG=${piperJson}
JARVIS_FAST_MODEL=llama3.2:latest
JARVIS_SMART_MODEL=llama3.2:latest
VITE_OLLAMA_ENABLED=1
VITE_OLLAMA_MODEL=llama3.2:latest
`
  writeFileSync(ENV_LOCAL, env)
  log(`Wrote ${ENV_LOCAL}`)
  log('Done. Run: npm run dev')
}

main().catch((e) => {
  console.error(e.message || e)
  process.exit(1)
})
